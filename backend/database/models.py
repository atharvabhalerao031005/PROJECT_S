"""SQLAlchemy models and session configuration for Multimodal Attendance Telemetry with SQLite WAL Mode."""
from datetime import datetime
from typing import Generator
import os

from sqlalchemy import (
    Column,
    Integer,
    Float,
    String,
    DateTime,
    create_engine,
    event,
    text,
)
from sqlalchemy.orm import declarative_base, sessionmaker, Session

DATABASE_URL = os.getenv("DATABASE_URL")
if not DATABASE_URL:
    DB_PATH = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "attendance_telemetry.db"))
    DATABASE_URL = f"sqlite:///{DB_PATH}"

connect_args = {"check_same_thread": False} if DATABASE_URL.startswith("sqlite") else {}
engine = create_engine(
    DATABASE_URL,
    connect_args=connect_args,
)

# Enable SQLite Write-Ahead Logging (WAL) mode for concurrency and durability
if DATABASE_URL.startswith("sqlite"):
    @event.listens_for(engine, "connect")
    def set_sqlite_wal(dbapi_connection, connection_record):
        cursor = dbapi_connection.cursor()
        cursor.execute("PRAGMA journal_mode=WAL;")
        cursor.execute("PRAGMA synchronous=NORMAL;")
        cursor.close()

SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
Base = declarative_base()


class AttendanceLog(Base):
    """Stores verified and in-progress participant attendance."""
    __tablename__ = "attendance_logs"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    session_id = Column(String(64), index=True, default="studio-morning-session")
    participant_id = Column(String(64), index=True)
    first_seen = Column(DateTime, default=datetime.utcnow)
    last_seen = Column(DateTime, default=datetime.utcnow)
    timestamp = Column(DateTime, default=datetime.utcnow, index=True)
    sustained_seconds = Column(Float, default=0.0)
    status = Column(String(32), default="Tracking...")  # "Verified Present", "Tracking...", "Transient / Ignored"


class EngagementSession(Base):
    """Granular time-series records of multimodal engagement fusion and session telemetry."""
    __tablename__ = "engagement_sessions"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    session_id = Column(String(64), index=True, default="studio-morning-session")
    timestamp = Column(DateTime, default=datetime.utcnow, index=True)
    active_faces = Column(Integer, default=0)
    head_pose_score = Column(Float, default=0.0)
    movement_score = Column(Float, default=0.0)
    inactivity_penalty = Column(Float, default=0.0)
    audio_rms_score = Column(Float, default=0.0)
    fused_score = Column(Float, default=0.0)
    trend = Column(String(64), default="Steady Plateau")


class AIInsight(Base):
    """Pedagogical decisions generated by Groq, Gemini, or the offline heuristic agent."""
    __tablename__ = "ai_insights"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    session_id = Column(String(64), index=True, default="studio-morning-session")
    timestamp = Column(DateTime, default=datetime.utcnow, index=True)
    engagement_context = Column(String(255))
    suggestion_text = Column(String(1024))
    pacing_action = Column(String(128))
    provider = Column(String(64), default="Offline Heuristic Engine (Local)")


# Aliases for backward compatibility with existing tests and modules
EngagementMetric = EngagementSession
TeachingSuggestion = AIInsight


